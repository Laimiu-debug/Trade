import { chromium, expect } from '@playwright/test'

const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:8011/rebuild.html')
  await page.getByRole('heading', { name: '创建第一个账户' }).waitFor()
  await page.getByRole('textbox', { name: '账户名称' }).fill('持仓快照浏览器测试')
  await page.getByRole('button', { name: '创建实盘账户' }).click()
  await page.getByRole('button', { name: '资金流水' }).click()
  await page.getByLabel('日期').fill('2025-01-01')
  await page.getByLabel('类型').selectOption('initial')
  await page.getByLabel('金额').fill('10000')
  await page.getByRole('button', { name: '保存流水' }).click()
  await page.getByRole('button', { name: '资产快照' }).click()
  await page.getByLabel('日期').fill('2025-01-02')
  await page.getByLabel('总资产').fill('10000')
  await page.getByLabel('可用现金（可选）').fill('7000')
  await page.getByRole('button', { name: '添加持仓' }).click()
  await page.getByLabel('持仓1代码').fill('600000')
  await page.getByLabel('持仓1名称').fill('测试股')
  await page.getByLabel('持仓1数量').fill('100')
  await page.getByLabel('持仓1市值').fill('3000')
  await page.getByText('明细市值合计 ¥ 3000.00').waitFor()
  await page.getByRole('button', { name: '保存快照' }).click()
  await page.getByText('1 项').waitFor()
  await page.getByRole('button', { name: '编辑' }).click()
  await expect(page.getByLabel('持仓1代码')).toHaveValue('600000')
  await page.getByLabel('持仓1市值').fill('3100')
  await page.getByLabel('持仓市值（可选）').fill('')
  await page.getByLabel('总资产').fill('10100')
  await page.getByRole('button', { name: '保存快照' }).click()
  await page.getByText('¥ 10100.00').waitFor()
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('browser smoke: position detail snapshot and correction')
} finally {
  await browser.close()
}
