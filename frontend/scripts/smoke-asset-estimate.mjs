import { chromium, expect } from '@playwright/test'

const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:8011/rebuild.html')
  await page.getByRole('heading', { name: '创建第一个账户' }).waitFor()
  await page.getByRole('textbox', { name: '账户名称' }).fill('资产估算浏览器测试')
  await page.getByRole('button', { name: '创建实盘账户' }).click()
  await page.getByRole('button', { name: '资金流水' }).click()
  await page.getByLabel('日期').fill('2025-01-01')
  await page.getByLabel('类型').selectOption('initial')
  await page.getByLabel('金额').fill('10000')
  await page.getByRole('button', { name: '保存流水' }).click()
  await page.getByRole('button', { name: '交易流水' }).click()
  const trade = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '新增交易' }) })
  await trade.getByLabel('交易日期').fill('2025-01-02')
  await trade.getByLabel('证券代码').fill('600000')
  await trade.getByLabel('价格').fill('10')
  await trade.getByRole('button', { name: '新增交易' }).click()
  await page.getByRole('button', { name: '行情样本' }).click()
  await page.getByRole('navigation', { name: '行情页面' }).getByRole('button', { name: '导入样本', exact: true }).click()
  const importer = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '导入固定样本' }) })
  await importer.getByLabel('证券代码').fill('600000')
  await importer.getByLabel('CSV 内容').fill('date,open,high,low,close,volume,available_at\n2025-01-02,10,10,10,10,1000,2025-01-02T15:00:00+00:00\n2025-01-03,11,11,11,11,1000,2025-01-03T15:00:00+00:00')
  await importer.getByRole('button', { name: '保存不可变样本' }).click()
  await page.getByText('不可变行情样本已保存').waitFor()
  await page.getByRole('button', { name: '资产快照' }).click()
  await page.getByLabel('日期').fill('2025-01-03')
  const panel = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '根据流水与行情估算资产' }) })
  await panel.getByLabel('600000 行情样本').selectOption({ index: 1 })
  await panel.getByRole('button', { name: '估算资产' }).click()
  await panel.getByText('估算总资产 ¥ 10094.99').waitFor()
  await panel.getByRole('button', { name: '把估算值填入表单' }).click()
  await expect(page.getByLabel('总资产')).toHaveValue('10094.99')
  await page.getByRole('button', { name: '保存快照' }).click()
  await page.getByText('1 项').waitFor()
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('browser smoke: frozen quote asset estimate, explicit form fill, snapshot save')
} finally {
  await browser.close()
}
